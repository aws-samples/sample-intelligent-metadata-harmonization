"""
Tests for markdown report generation with cost metrics.

This module tests that cost metrics are properly included in markdown
reports generated by ReportGenerator.
"""

from datetime import datetime
from pathlib import Path
from tempfile import TemporaryDirectory


from metadata_harmonization_eval.models import (
    AccuracyMetrics,
    CostMetrics,
    ConfidenceMetrics,
    ErrorAnalysis,
    EvaluationResult,
    NodeMetrics,
    PerformanceMetrics,
)
from metadata_harmonization_eval.report_generator import ReportGenerator


class TestMarkdownReportCostMetrics:
    """Tests for cost metrics in markdown reports."""

    def test_generate_markdown_report_includes_cost_section(self):
        """Test that markdown report includes cost metrics section."""
        # Create cost metrics
        cost_metrics = CostMetrics(
            llm_input_tokens=50000,
            llm_output_tokens=15000,
            llm_total_tokens=65000,
            llm_input_cost=0.04,
            llm_output_cost=0.06,
            llm_total_cost=0.10,
            llm_api_calls=25,
            embedding_tokens=1170000,
            embedding_cost=0.0234,
            embedding_api_calls=150,
            total_cost=0.1234,
            cost_per_error_detected=0.0012,
            llm_model_id="amazon.nova-pro-v1:0",
            embedding_model_id="amazon.titan-embed-text-v2:0",
        )

        # Create evaluation result with cost metrics
        result = EvaluationResult(
            dataset_name="test_dataset",
            timestamp=datetime(2025, 11, 21, 12, 0, 0),
            session_id="test-session",
            program_id="test-program",
            core_id="test-core",
            error_rate=0.4,
            accuracy_metrics=AccuracyMetrics(
                precision=0.9,
                recall=0.85,
                f1_score=0.87,
                true_positives=85,
                false_positives=10,
                false_negatives=15,
                true_negatives=890,
                accuracy=0.975,
            ),
            performance_metrics=PerformanceMetrics(
                total_duration_seconds=120.5,
                per_record_duration_ms=120.5,
                records_per_second=8.3,
                schema_alignment_duration=10.0,
                validation_duration=50.0,
                prediction_duration=60.5,
                peak_memory_mb=512.0,
            ),
            confidence_metrics=ConfidenceMetrics(
                mean_confidence=0.75,
                median_confidence=0.80,
                std_deviation=0.15,
                min_confidence=0.2,
                max_confidence=0.99,
                high_confidence_accuracy=0.95,
                low_confidence_accuracy=0.65,
            ),
            error_analysis=ErrorAnalysis(total_errors=100, detected_errors=85, missed_errors=15, false_alarms=10),
            total_records=1000,
            total_ground_truth_errors=100,
            cost_metrics=cost_metrics,
        )

        # Generate markdown report
        with TemporaryDirectory() as tmpdir:
            output_dir = Path(tmpdir)
            report_gen = ReportGenerator(output_dir)
            output_path = output_dir / "test_report.md"

            report_gen.generate_markdown_report(result, output_path)

            # Read the generated markdown file
            with open(output_path, "r") as f:
                markdown_content = f.read()

            # Verify cost metrics section is present
            assert "## Cost Metrics" in markdown_content
            assert "### Overall Cost Summary" in markdown_content

            # Verify total cost is displayed
            assert "$0.1234" in markdown_content

            # Verify LLM cost breakdown
            assert "LLM Cost" in markdown_content
            assert "$0.1000" in markdown_content
            assert "50,000" in markdown_content  # Input tokens
            assert "15,000" in markdown_content  # Output tokens
            assert "$0.0400" in markdown_content  # Input cost
            assert "$0.0600" in markdown_content  # Output cost

            # Verify embedding cost breakdown
            assert "Embedding Cost" in markdown_content
            assert "$0.0234" in markdown_content
            assert "1,170,000" in markdown_content  # Embedding tokens

            # Verify cost per error detected
            assert "Cost per Error Detected" in markdown_content
            assert "$0.0012" in markdown_content

